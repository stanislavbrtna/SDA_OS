// power options overlay
uint16_t main_menu_overlay;
uint8_t  main_menu_overlay_flag;


void sda_mm_overlay_init() {
  if (main_menu_overlay_flag == 0 && svpSGlobal.sdaDeviceLock == DEVICE_UNLOCKED) {
    destroyOverlay();
    sda_mm_overlay_handle(1);
    setOverlayScreen(main_menu_overlay, &sda_sys_con);
    setOverlayDestructor(sda_mm_destructor);
    main_menu_overlay_flag = 1;
    setOverlayPos(0, 32, 160 + 32, 128 + 32);
  } else {
    destroyOverlay();
  }
}


void sda_mm_destructor() {
  gr2_destroy(main_menu_overlay, &sda_sys_con);
  setRedrawFlag();
  main_menu_overlay_flag = 0;
  main_menu_overlay = 0xFFFF;
}


uint8_t sda_mm_overlay_shown() {
  return main_menu_overlay_flag;
}


void switch_to_homescreen() {
  if(sda_get_top_slot() != SDA_SLOT_HOMESCREEN) {
    svmHandleSlotSwitch();
    svpSGlobal.systemXBtnClick = 0;
    svpSGlobal.systemXBtnVisible = 0;

    sda_set_landscape(0);
    sda_keyboard_hide();
    
    sda_slot_on_top(SDA_SLOT_HOMESCREEN);
    
    svp_switch_main_dir();
    svp_chdir((uint8_t *)"APPS");
  }
}


void sda_mm_overlay_handle(uint8_t init) {
  static uint16_t taskManagerBtn;
  static uint16_t lockBtn;
  static uint16_t settingsBtn;

  static uint16_t quickBtn;
  static uint16_t homeBtn;
  static uint16_t appsBtn;

  if (init == 1) {
    main_menu_overlay = gr2_add_screen(&sda_sys_con);
    gr2_set_x_cell(main_menu_overlay, 16, &sda_sys_con);
    gr2_set_y_cell(main_menu_overlay, 16, &sda_sys_con);
    gr2_set_relative_init(1, &sda_sys_con);
    
    taskManagerBtn = gr2_add_button(
      0, 0, 12, 2,
      ASCR_RUNNING_APP,
      main_menu_overlay,
      &sda_sys_con
    );
    gr2_set_rounded(taskManagerBtn, 0, &sda_sys_con);
    
    lockBtn  = gr2_add_button(
      0, 2, 12, 2,
      SCR_LOCK_DEVICE,
      main_menu_overlay,
      &sda_sys_con
    );
    gr2_set_rounded(lockBtn, 0, &sda_sys_con);
    
    settingsBtn  = gr2_add_button(
      0, 4, 12, 2,
      ASCR_SETTINGS_BTN,
      main_menu_overlay,
      &sda_sys_con
    );
    gr2_set_rounded(settingsBtn, 0, &sda_sys_con);

    if (svp_crypto_get_if_set_up() == 0) {
      gr2_set_grayout(lockBtn, 1, &sda_sys_con);
    }

    quickBtn = gr2_add_button(
      0, 6, 4, 4,
      "",
      main_menu_overlay,
      &sda_sys_con
    );
    gr2_set_str2(quickBtn, launch, &sda_sys_con);
    gr2_set_param(quickBtn, -4, &sda_sys_con);

    homeBtn = gr2_add_button(
      4, 6, 4, 4,
      "",
      main_menu_overlay,
      &sda_sys_con
    );
    gr2_set_str2(homeBtn, home, &sda_sys_con);
    gr2_set_param(homeBtn, -4, &sda_sys_con);

    appsBtn = gr2_add_button(
      8, 6, 4, 4,
      "",
      main_menu_overlay,
      &sda_sys_con
    );
    gr2_set_str2(appsBtn, apps, &sda_sys_con);
    gr2_set_param(appsBtn, -4, &sda_sys_con);

    gr2_set_relative_init(0, &sda_sys_con);
    return;
  }

  if (gr2_clicked(taskManagerBtn, &sda_sys_con)) {
    taskSwitcherOpen();
    return;
  }

  if (gr2_clicked(lockBtn, &sda_sys_con)) {
    switch_to_homescreen();
    sda_set_device_lock(1);
    destroyOverlay();
    return;
  }

  if (gr2_clicked(settingsBtn, &sda_sys_con)) {
    svmHandleSlotSwitch();
    sda_settings_open();
    destroyOverlay();
    return;
  }

  if (gr2_clicked(homeBtn, &sda_sys_con)) {
    switch_to_homescreen();
    destroyOverlay();
    return;
  }

  if (gr2_clicked(appsBtn, &sda_sys_con)) {
    svmHandleSlotSwitch();
    svp_switch_main_dir();
    svp_chdir((uint8_t *)"APPS");
    sda_slot_on_top(SDA_SLOT_APPLIST);
    destroyOverlay();
    return;
  }

  // TODO: QuickLaunch

  if (svpSGlobal.lcdState == LCD_OFF) {
    destroyOverlay();
    return;
  }

  sda_screen_button_handler(main_menu_overlay, taskManagerBtn, &sda_sys_con);
}